// The storage register read, tested from the frames the hardware exchanged
// (both RC-5s and the RC-500, 2026-09-22..25) — the bytes below are those
// captures, not the builder's output. The rules this suite exists for:
//
//   - the request is the exact RQ1 the pedal answered;
//   - only the pedal's DT1 to 7F 70 00 00, for OUR model, with a good
//     checksum, whole, is an answer — everything else on the bus is not,
//     and is ignored rather than mistaken for one;
//   - 00 / 01 / 02 are the three states; any other byte is an error that
//     names it, never "idle".

#include "support.hpp"

#include <loopercat/StorageRegister.hpp>

#include <cstdint>
#include <vector>

using namespace loopercat;

namespace {

using Bytes = std::vector<std::uint8_t>;

std::optional<storage::State> parse(const Bytes& frame) { return storage::parseReply(frame); }

bool is(const Bytes& frame, storage::State state)
{
    const auto parsed = parse(frame);
    return parsed.has_value() && *parsed == state;
}

// The pedal's answers, as captured (device 10, model 76, DT1, register, value, checksum).
const Bytes kIdle { 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x11, 0xF7 };
const Bytes kInStorage { 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x01, 0x10, 0xF7 };
const Bytes kBusy { 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x02, 0x0F, 0xF7 };

} // namespace

int main()
{
    // --- the request, byte for byte as the pedal answered it ---

    CHECK((storage::readRequest()
           == Bytes { 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x11, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x00,
                      0x00, 0x01, 0x10, 0xF7 }));

    // --- the three states the hardware has shown ---

    CHECK(is(kIdle, storage::State::idle));
    CHECK(is(kInStorage, storage::State::inStorage));
    CHECK(is(kBusy, storage::State::busy));

    // --- not the answer: ignored, so the caller keeps listening ---

    // The RC-500's answer to the same question: right shape, other model.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x77, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x11, 0xF7 }));
    // The ready flag the pedal raises on entering storage: next-door address.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x01, 0x01, 0x0F, 0xF7 }));
    // Our own request, should it echo: RQ1, not DT1 — and a request-shaped
    // frame of the answer's length is still a request, whatever it carries.
    CHECK(!parse(storage::readRequest()));
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x11, 0x7F, 0x70, 0x00, 0x00, 0x02, 0x0F, 0xF7 }));
    // Another address is not the register, even when the bytes after it add
    // up to what the register's answer would carry.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x01, 0x02, 0x0F, 0xF7 }));
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x71, 0x00, 0x00, 0x00, 0x10, 0xF7 }));
    // A wrong checksum: the byte says 00, the sum says otherwise.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x10, 0xF7 }));
    // Cut short: no terminator, or the tail missing.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x11 }));
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00 }));
    CHECK(!parse({}));
    // Padded: two data bytes where the answer carries one.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x01, 0x10, 0xF7 }));
    // The MIDI Identity Reply the same pedal sends — 15 bytes too, not Roland's dialect.
    CHECK(!parse({ 0xF0, 0x7E, 0x10, 0x06, 0x02, 0x41, 0x76, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xF7 }));
    // Another device id: the pedal answers as 10.
    CHECK(!parse({ 0xF0, 0x41, 0x7F, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x11, 0xF7 }));
    // Not framed at all.
    CHECK(!parse({ 0x41, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x11, 0xF7 }));
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x00, 0x11, 0x00 }));
    // An 8-bit byte where the value sits: not a sysex payload, not an answer, not a crash.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x80, 0x11, 0xF7 }));

    // --- an unknown state is named, never defaulted ---

    CHECK_THROWS(parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x03, 0x0E, 0xF7 }),
                 "reads 0x03");
    CHECK_THROWS(parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x7F, 0x12, 0xF7 }),
                 "reads 0x7f");
    // ...but only when the frame is otherwise the answer: an unknown value
    // behind a wrong checksum is noise, not a verdict.
    CHECK(!parse({ 0xF0, 0x41, 0x10, 0x00, 0x00, 0x00, 0x76, 0x12, 0x7F, 0x70, 0x00, 0x00, 0x03, 0x11, 0xF7 }));

    // --- words for the probe ---

    CHECK_EQ(std::string(storage::describe(storage::State::idle)), "idle (00)");
    CHECK_EQ(std::string(storage::describe(storage::State::inStorage)), "in storage mode (01)");
    CHECK_EQ(std::string(storage::describe(storage::State::busy)), "busy (02): playing, or an unsaved take");

    return testkit::summary("storage_register");
}
